NAMES = {'-': 'dash', '.': 'dot', '_': 'under'}
def runs(px):
    rows = {}
    for x, y in px: rows.setdefault(y, []).append(x)
    out = []
    for y, xs in sorted(rows.items()):
        xs.sort(); s = p = xs[0]
        for v in xs[1:] + [None]:
            if v == p + 1: p = v; continue
            out.append((s, y, p - s + 1)); s = p = v
    return out
def rects(px, c): return ''.join(f'<rect x="{x}" y="{y}" width="{w}" height="1" fill="{c}"/>' for x, y, w in runs(px))
if __name__ == '__main__':
    out = sys.argv[1] + '/icons'; os.makedirs(out, exist_ok=True)
    for ch, gl in F.items():
        if not gl: continue
        fill = {(1 + x, 1 + y) for y, r in enumerate(gl.split('/')) for x, c in enumerate(r) if c == '#'}
        hdr = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" shape-rendering="crispEdges">'
        open(f'{out}/gf-{NAMES.get(ch, ch)}.svg', 'w').write(hdr + rects(fill, 'currentColor') + '</svg>')
